package dev.codex.android.tools

import dev.codex.android.core.CodexJson
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/**
 * Webapp testing (tool: `webapp_test`, skill: webapp-testing).
 *
 * Two layers, in order:
 * 1. **Playwright (primary).** A generated Node script (no project
 *    dependency beyond the globally staged `playwright` package) opens
 *    the URL in system Chromium and runs the caller's checks — a CSS
 *    selector must exist, and optional expected text must appear in it.
 *    The script prints exactly one machine-readable line,
 *    `WEBAPP_TEST_RESULT {...}`, and exits 0 only when every check passes.
 *    Playwright is staged by [dev.codex.android.linux.BuilderToolchainStaging]
 *    (`node` toolchain + `apk add chromium` + `npm install -g playwright`);
 *    the script points Playwright at the system Chromium via
 *    `PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH` instead of downloading
 *    browsers, because `playwright install` (apt-based) cannot run on
 *    Alpine.
 * 2. **VerificationBrowser (fallback).** When Playwright is not staged
 *    and staging fails, the tool falls back to the app's existing
 *    `VerificationBrowser` (WebView: load + DOM snapshot + console logs)
 *    through the caller-supplied [browserCheck] seam — and says so
 *    plainly in the result. It never claims a Playwright pass it did not
 *    run.
 *
 * Pure logic here (script generation + output parsing); the tool in
 * [BuilderTools] owns the shell. No Android APIs in this file.
 */
data class WebCheck(
    val name: String,
    val selector: String,
    val expectText: String? = null,
)

data class WebAppTestResult(
    /** True only when the runner ran AND every check passed. */
    val ok: Boolean,
    /** "playwright" or "verification-browser" — which layer produced this. */
    val runner: String,
    val passed: Int,
    val failed: Int,
    /** Failing assertion per check, or the runner error. Empty when all pass. */
    val failures: List<String>,
    /** Short human-readable verdict, safe to hand to the model. */
    val summary: String,
)

object WebAppTesting {

    /** The one machine-readable line the generated script prints. */
    const val RESULT_MARKER = "WEBAPP_TEST_RESULT"

    /** File name (under `webapp-tests/`) for a generated test script. */
    fun scriptFileName(url: String): String {
        val slug = url.lowercase()
            .removePrefix("https://").removePrefix("http://").removePrefix("file://")
            .map { if (it.isLetterOrDigit()) it else '-' }
            .joinToString("").trim('-').take(40).ifBlank { "page" }
        return "test-$slug.cjs"
    }

    /**
     * Builds the Node Playwright script for [url] and [checks]. When
     * [checks] is empty the script only proves the page loads (HTTP 2xx,
     * non-empty title) and reports console errors.
     */
    fun buildPlaywrightScript(url: String, checks: List<WebCheck>): String {
        val checksJson = buildString {
            append("[")
            checks.forEachIndexed { i, check ->
                if (i > 0) append(",")
                append("{name:${jsString(check.name)},selector:${jsString(check.selector)}")
                check.expectText?.let { append(",expectText:${jsString(it)}") }
                append("}")
            }
            append("]")
        }
        return """
            |// Generated by Codex webapp_test — do not edit by hand.
            |// Usage: node ${scriptFileName(url)} "<url>"
            |const { chromium } = require("playwright");
            |
            |const URL = process.argv[2];
            |const CHECKS = $checksJson;
            |
            |function report(passed, failed, failures) {
            |  console.log("WEBAPP_TEST_RESULT " + JSON.stringify({ passed, failed, failures }));
            |}
            |
            |(async () => {
            |  let browser;
            |  try {
            |    browser = await chromium.launch({
            |      executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined,
            |      args: ["--no-sandbox"],
            |    });
            |  } catch (e) {
            |    console.log("WEBAPP_TEST_RESULT " + JSON.stringify({
            |      passed: 0, failed: 1,
            |      failures: ["browser launch failed: " + (e && e.message ? e.message : String(e))],
            |    }));
            |    process.exit(1);
            |  }
            |  const failures = [];
            |  let passed = 0;
            |  try {
            |    const page = await browser.newPage();
            |    const consoleErrors = [];
            |    page.on("console", (m) => { if (m.type() === "error") consoleErrors.push(m.text()); });
            |    page.on("pageerror", (e) => consoleErrors.push(String(e)));
            |    const response = await page.goto(URL, { waitUntil: "networkidle", timeout: 30000 });
            |    const status = response ? response.status() : 0;
            |    if (status < 200 || status >= 400) {
            |      failures.push("page did not load: HTTP " + status + " for " + URL);
            |    } else if (CHECKS.length === 0) {
            |      const title = await page.title();
            |      if (!title) failures.push("page loaded but has an empty title");
            |      else passed++;
            |    }
            |    for (const check of CHECKS) {
            |      try {
            |        const el = await page.waitForSelector(check.selector, { timeout: 5000 });
            |        if (check.expectText !== undefined) {
            |          const text = (await el.textContent()) || "";
            |          if (!text.includes(check.expectText)) {
            |            failures.push(check.name + ": selector '" + check.selector +
            |              "' found but text does not contain '" + check.expectText +
            |              "' (got: '" + text.slice(0, 120) + "')");
            |            continue;
            |          }
            |        }
            |        passed++;
            |      } catch (e) {
            |        failures.push(check.name + ": selector '" + check.selector + "' not found on " + URL);
            |      }
            |    }
            |    if (consoleErrors.length > 0) {
            |      failures.push("console errors on page: " + consoleErrors.slice(0, 3).join(" | "));
            |    }
            |    await browser.close();
            |  } catch (e) {
            |    failures.push("test run failed: " + (e && e.message ? e.message : String(e)));
            |    try { await browser.close(); } catch (ignored) {}
            |  }
            |  report(passed, failures.length, failures);
            |  process.exit(failures.length === 0 ? 0 : 1);
            |})();
            |
        """.trimMargin()
    }

    /**
     * Parses a Playwright run: [exitCode] and the combined stdout+stderr.
     * Looks for the `WEBAPP_TEST_RESULT {...}` line; when it is missing
     * the run itself failed (bad script, missing module, timeout) and the
     * result says so with the raw tail attached.
     */
    fun parsePlaywrightOutput(exitCode: Int, output: String): WebAppTestResult {
        val line = output.lineSequence()
            .firstOrNull { it.startsWith(RESULT_MARKER) }
        if (line == null) {
            return WebAppTestResult(
                ok = false,
                runner = "playwright",
                passed = 0,
                failed = 1,
                failures = listOf(
                    "Playwright produced no test result (exit $exitCode). " +
                        "Raw output tail: ${output.takeLast(500).ifBlank { "(empty)" }}",
                ),
                summary = "Playwright run failed: no test result was produced (exit $exitCode).",
            )
        }
        val parsed = runCatching {
            CodexJson.parseToJsonElement(line.removePrefix(RESULT_MARKER).trim()).jsonObject
        }.getOrNull()
        if (parsed == null) {
            return WebAppTestResult(
                ok = false,
                runner = "playwright",
                passed = 0,
                failed = 1,
                failures = listOf("Unparseable test result line: ${line.take(300)}"),
                summary = "Playwright run failed: the test result line could not be parsed.",
            )
        }
        val passed = parsed["passed"]?.jsonPrimitive?.contentOrNull?.toIntOrNull() ?: 0
        val failed = parsed["failed"]?.jsonPrimitive?.contentOrNull?.toIntOrNull() ?: 0
        val failures = parsed["failures"]?.jsonArray
            ?.mapNotNull { it.jsonPrimitive.contentOrNull } ?: emptyList()
        val allPassed = exitCode == 0 && failed == 0
        return WebAppTestResult(
            ok = allPassed,
            runner = "playwright",
            passed = passed,
            failed = failed,
            failures = failures,
            summary = if (allPassed) {
                "Playwright: all $passed check(s) passed."
            } else {
                "Playwright: $passed passed, $failed failed. " + failures.joinToString("; ")
            },
        )
    }

    /** True when [output] shows the `playwright` module is not installed. */
    fun isPlaywrightMissing(output: String): Boolean =
        "Cannot find module 'playwright'" in output ||
            "Cannot find module \"playwright\"" in output

    /**
     * Parses the `checks` argument of the `webapp_test` tool: a JSON array
     * of `{name, selector, expectText?}` objects. Throws
     * [IllegalArgumentException] on malformed JSON or a case without
     * `name`/`selector`.
     */
    fun parseChecks(checksJson: String): List<WebCheck> {
        if (checksJson.isBlank()) return emptyList()
        val element = try {
            CodexJson.parseToJsonElement(checksJson)
        } catch (e: Exception) {
            throw IllegalArgumentException("checks must be a JSON array: ${e.message}")
        }
        val array = try {
            element.jsonArray
        } catch (e: Exception) {
            throw IllegalArgumentException("checks must be a JSON array of check objects.")
        }
        return array.mapIndexed { index, item ->
            val obj: JsonObject = try {
                item.jsonObject
            } catch (e: Exception) {
                throw IllegalArgumentException("checks[$index] must be an object with name and selector.")
            }
            val name = obj["name"]?.jsonPrimitive?.contentOrNull?.trim().orEmpty()
            val selector = obj["selector"]?.jsonPrimitive?.contentOrNull?.trim().orEmpty()
            if (name.isBlank()) throw IllegalArgumentException("checks[$index] is missing 'name'.")
            if (selector.isBlank()) throw IllegalArgumentException("checks[$index] ('$name') is missing 'selector'.")
            WebCheck(
                name = name,
                selector = selector,
                expectText = obj["expectText"]?.jsonPrimitive?.contentOrNull,
            )
        }
    }

    private fun jsString(value: String): String =
        "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\""
}
